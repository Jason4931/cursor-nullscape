export let PATTERNS = WeightedPatterns;
export function changePatterns(v) {
  if (v == "final") {
    PATTERNS = WeightedFinalPatterns;
    latestPattern = v;
  } else if (v == "ice") {
    PATTERNS = RawIcePatterns;
  } else if (v == "normal") {
    PATTERNS = WeightedPatterns;
    latestPattern = v;
  } else {
    if (latestPattern === "final") {
      PATTERNS = WeightedFinalPatterns;
    } else {
      PATTERNS = WeightedPatterns;
    }
  }
}
