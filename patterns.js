const WeightedPatterns = [];
for (const pattern of RawPatterns) {
  const weight = pattern[0][0] === 100 ? 1 : 5;

  for (let i = 0; i < weight; i++) {
    WeightedPatterns.push(pattern);
  }
}

const FilteredPatterns = RawPatterns.filter((pattern) => {
  const h = pattern.length;
  const w = pattern[0].length;
  return !(h === 27 && w === 27);
});
const WeightedFinalPatterns = [...FilteredPatterns, ...RawFinalPatterns];

let PatternRotation = [
  {
    pattern: WeightedPatterns,
    duration: 0,
  },
];
let latestPatRot = PatternRotation;
export let PATTERNS = WeightedPatterns;
let rotationIndex = 0;
let rotationElapsed = 0;
setInterval(() => {
  const entry = PatternRotation[rotationIndex];
  if (!entry || entry.duration === 0) return;
  rotationElapsed++;
  if (rotationElapsed >= entry.duration) {
    rotationElapsed = 0;
    rotationIndex = (rotationIndex + 1) % PatternRotation.length;
    PATTERNS = PatternRotation[rotationIndex].pattern;
  }
}, 1000);
export function changePatterns(v) {
  if (v == "ice") {
    let iceExist = false;
    let gardenExist = false;
    PatternRotation.forEach((e) => {
      if (e.pattern == RawIcePatterns) iceExist = true;
      else if (e.pattern == RawGardenPatterns) gardenExist = true;
    });
    if (!iceExist) {
      PatternRotation.push({
        pattern: RawIcePatterns,
        duration: 10,
      });
      PatternRotation.forEach((e) => {
        if (e.pattern == WeightedPatterns) e.duration = gardenExist ? 30 : 50;
      });
    }
    latestPatRot = PatternRotation;
  }
  if (v == "garden") {
    let iceExist = false;
    let gardenExist = false;
    PatternRotation.forEach((e) => {
      if (e.pattern == RawIcePatterns) iceExist = true;
      else if (e.pattern == RawGardenPatterns) gardenExist = true;
    });
    if (!gardenExist) {
      PatternRotation.push({
        pattern: RawGardenPatterns,
        duration: 20,
      });
      PatternRotation.forEach((e) => {
        if (e.pattern == WeightedPatterns) e.duration = iceExist ? 30 : 40;
      });
    }
    latestPatRot = PatternRotation;
  }
  if (v == "final") {
    PatternRotation = [
      {
        pattern: WeightedFinalPatterns,
        duration: 0,
      },
    ];
  }
  if (v == "none") {
    PatternRotation = [
      {
        pattern: WeightedPatterns,
        duration: 0,
      },
    ];
  }
  if (v == "normal") {
    PatternRotation = latestPatRot;
  }
  if (v == "passage") {
    PatternRotation = [
      {
        pattern: RawPassagePatterns,
        duration: 0,
      },
    ];
  }
  if (v) {
    rotationIndex = 0;
    rotationElapsed = 60;
    PATTERNS = PatternRotation[0].pattern;
  }
}
